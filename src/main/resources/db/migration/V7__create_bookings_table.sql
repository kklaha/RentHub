ALTER TABLE orders DROP COLUMN IF EXISTS start_time;
ALTER TABLE orders DROP COLUMN IF EXISTS end_time;
ALTER TABLE items ADD COLUMN item_type varchar(20);
ALTER TABLE orders DROP CONSTRAINT if exists check_order_dates;
ALTER TABLE items drop column if exists category_id;
create table bookings(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    item_id BIGINT references items(id) on delete cascade,
    category varchar(32) not null,
    renter_id bigint references users(id) on delete cascade ,
    start_time timestamptz not null,
    end_time timestamptz not null ,
    status varchar(20) not null,
    total_price numeric(12,2) not null,
    created_at timestamptz not null default current_timestamp,
    CONSTRAINT check_order_dates
        CHECK (
            (start_time IS NULL AND end_time IS NULL)
                OR
            (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time))
);
drop table categories;
create unique index uq_confirmed_order_per_item
    on orders(item_id)
    where status in ('CONFIRMED', 'PAID');
